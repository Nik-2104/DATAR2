import json
from typing import Any

from app.mcp.registry import create_mcp_client
from app.models import DatasetCandidate, DatasetRequirement


class DatasetSearchService:
    """
    Connects Gemini's dataset requirements with the MCP servers.

    Flow:

        DatasetRequirement
                ↓
        Search queries
                ↓
        MCP servers
                ↓
        Raw search results
                ↓
        DatasetCandidate objects
    """

    def __init__(self):
        self.mcp_client = create_mcp_client()

    # ============================================================
    # Public Search Method
    # ============================================================

    async def search(
        self,
        requirement: DatasetRequirement,
    ) -> list[DatasetCandidate]:
        """
        Search available MCP servers using the queries
        generated by Gemini.
        """

        candidates: list[DatasetCandidate] = []

        queries = requirement.search_queries

        if not queries:
            queries = [
                self._build_fallback_query(requirement)
            ]

        # Remove duplicate queries
        queries = list(dict.fromkeys(queries))

        for query in queries:

            # ----------------------------------------------------
            # Kaggle
            # ----------------------------------------------------

            kaggle_results = await self._search_kaggle(
                query=query,
            )

            candidates.extend(
                kaggle_results
            )

            # ----------------------------------------------------
            # Hugging Face
            # ----------------------------------------------------

            hf_results = await self._search_huggingface(
                query=query,
            )

            candidates.extend(
                hf_results
            )

        return self._deduplicate(
            candidates
        )

    # ============================================================
    # Kaggle Search
    # ============================================================

    async def _search_kaggle(
        self,
        query: str,
    ) -> list[DatasetCandidate]:

        try:

            result = await self.mcp_client.call_tool(
                server_name="kaggle",
                tool_name="search_datasets",
                arguments={
                    "request": {
                        "search": query,
                        "size": "All",
                        "fileType": "All",
                        "sortBy": "Relevance",
                        "pageSize": 20,
                    }
                },
            )

            return self._parse_kaggle_result(
                result
            )

        except Exception as exc:

            print(
                f"[Kaggle MCP] Search failed for "
                f"'{query}': {exc}"
            )

            return []

    # ============================================================
    # Hugging Face Search
    # ============================================================

    async def _search_huggingface(
        self,
        query: str,
    ) -> list[DatasetCandidate]:
    
        try:
    
            print()
            print("=" * 60)
            print(f"[HF MCP] Searching: {query}")
            print("=" * 60)
    
            result = await self.mcp_client.call_tool(
                server_name="huggingface",
                tool_name="hub_repo_search",
                arguments={
                    "query": query,
                    "repo_types": ["dataset"],
                    "sort": "downloads",
                    "limit": 20,
                },
            )
    
            print("[HF MCP] RAW RESULT:")
            print(result)
    
            parsed = self._parse_huggingface_result(result)
    
            print(
                f"[HF MCP] Parsed candidates: {len(parsed)}"
            )
    
            for candidate in parsed:
                print(
                    f"  -> {candidate.dataset_id}"
                )
    
            return parsed
    
        except Exception as exc:
    
            print(
                f"[Hugging Face MCP] Search failed for "
                f"'{query}': {exc}"
            )
    
            return []
    # ============================================================
    # Find HF Dataset Search Tool
    # ============================================================

    def _find_hf_search_tool(
        self,
        tools: list[dict[str, Any]],
    ) -> dict[str, Any] | None:

        preferred_names = [
            "search_datasets",
            "dataset_search",
            "search_dataset",
            "hub_search",
        ]

        for preferred in preferred_names:

            for tool in tools:

                if tool["name"].lower() == preferred:
                    return tool

        # Fallback: inspect tool names.
        for tool in tools:

            name = tool["name"].lower()

            if (
                "dataset" in name
                and "search" in name
            ):
                return tool

        return None

    # ============================================================
    # Build HF Arguments
    # ============================================================

    def _build_hf_arguments(
        self,
        schema: dict[str, Any],
        query: str,
    ) -> dict[str, Any]:

        properties = (
            schema
            .get("properties", {})
        )

        arguments = {}

        # Most MCP tools use "query".
        if "query" in properties:
            arguments["query"] = query

        # Some tools use "search".
        elif "search" in properties:
            arguments["search"] = query

        # Some tools use a nested request object.
        elif "request" in properties:

            request_schema = properties[
                "request"
            ]

            request_properties = request_schema.get(
                "properties",
                {},
            )

            if "query" in request_properties:
                arguments["request"] = {
                    "query": query
                }

            elif "search" in request_properties:
                arguments["request"] = {
                    "search": query
                }

        return arguments

    # ============================================================
    # Parse Kaggle Result
    # ============================================================

    def _parse_kaggle_result(
        self,
        result: Any,
    ) -> list[DatasetCandidate]:

        payload = self._extract_result_data(
            result
        )

        if payload is None:
            return []

        # Kaggle MCP may return structured data
        # or JSON inside a text content block.

        if isinstance(payload, dict):

            items = (
                payload.get("datasets")
                or payload.get("results")
                or payload.get("items")
                or []
            )

        elif isinstance(payload, list):

            items = payload

        else:
            return []

        candidates = []

        for item in items:

            if not isinstance(item, dict):
                continue

            dataset_id = (
                item.get("datasetRef")
                or item.get("ref")
                or item.get("id")
                or item.get("datasetId")
                or ""
            )

            name = (
                item.get("title")
                or item.get("name")
                or dataset_id
            )

            description = (
                item.get("description")
                or ""
            )

            candidate = DatasetCandidate(
                source="kaggle",
                dataset_id=str(dataset_id),
                name=str(name),
                description=str(description),
                downloads=self._to_int(
                    item.get("download_count")
                    or item.get("downloadCount")
                    or item.get("downloads")
                ),
                likes=self._to_int(
                    item.get("vote_count")
                    or item.get("voteCount")
                    or item.get("votes")
                    or item.get("likes")
                ),
            )

            candidates.append(candidate)

        return candidates

    # ============================================================
    # Parse Hugging Face Result
    # ============================================================

    def _parse_huggingface_result(
    self,
    result: Any,
    ) -> list[DatasetCandidate]:
    
        # HF MCP currently returns Markdown/text
        # inside TextContent.
    
        if not hasattr(result, "content"):
            return []
    
        candidates = []
    
        for content in result.content:
        
            text = getattr(
                content,
                "text",
                None,
            )
    
            if not text:
                continue
            
            lines = text.splitlines()
    
            current = None
    
            for line in lines:
            
                line = line.strip()
    
                # ------------------------------------------------
                # Dataset heading
                # Example:
                # ### UniDataPro/road-traffic-in-serbia...
                # ------------------------------------------------
    
                if line.startswith("### "):
                
                    if current:
                        candidates.append(
                            DatasetCandidate(
                                source="huggingface",
                                dataset_id=current["dataset_id"],
                                name=current["name"],
                                description=current["description"],
                                downloads=current["downloads"],
                                likes=current["likes"],
                                metadata=current["metadata"],
                            )
                        )
    
                    dataset_id = line[4:].strip()
    
                    current = {
                        "dataset_id": dataset_id,
                        "name": dataset_id,
                        "description": "",
                        "downloads": 0,
                        "likes": 0,
                        "metadata": {},
                    }
    
                    continue
                
                if current is None:
                    continue
                
                # ------------------------------------------------
                # Description
                # ------------------------------------------------
    
                if (
                    line
                    and not line.startswith("**")
                    and not line.startswith("---")
                    and not line.startswith("Dataset")
                    and not line.startswith("[")
                ):
    
                    if not current["description"]:
                        current["description"] = line
    
                # ------------------------------------------------
                # Author / Downloads / Likes
                # ------------------------------------------------
    
                if "**Author:**" in line:
                
                    parts = line.split("|")
    
                    for part in parts:
                    
                        part = part.strip()
    
                        if "**Downloads:**" in part:
                        
                            value = part.split(
                                "**Downloads:**",
                                1
                            )[1].strip()
    
                            try:
                                current["downloads"] = int(value)
                            except ValueError:
                                pass
                            
                        elif "**Likes:**" in part:
                        
                            value = part.split(
                                "**Likes:**",
                                1
                            )[1].strip()
    
                            try:
                                current["likes"] = int(value)
                            except ValueError:
                                pass
                            
                # ------------------------------------------------
                # Link
                # ------------------------------------------------
    
                if "**Link:**" in line:
                
                    link = line.split(
                        "**Link:**",
                        1
                    )[1].strip()
    
                    current["metadata"]["url"] = link
    
            # ----------------------------------------------------
            # Add final dataset
            # ----------------------------------------------------
    
            if current:
            
                candidates.append(
                    DatasetCandidate(
                        source="huggingface",
                        dataset_id=current["dataset_id"],
                        name=current["name"],
                        description=current["description"],
                        downloads=current["downloads"],
                        likes=current["likes"],
                        metadata=current["metadata"],
                    )
                )
    
        return candidates
    
    # --------------------------------------------------------
    # MCP CallToolResult
    # --------------------------------------------------------

        if hasattr(result, "structured_content"):

            structured = (
                result.structured_content
            )

            if structured is not None:
                return structured

        # --------------------------------------------------------
        # Content blocks
        # --------------------------------------------------------

        if hasattr(result, "content"):

            for content in result.content:

                text = getattr(
                    content,
                    "text",
                    None,
                )

                if not text:
                    continue

                try:
                    return json.loads(text)

                except json.JSONDecodeError:
                    continue

        # --------------------------------------------------------
        # Plain dictionaries
        # --------------------------------------------------------

        if isinstance(result, dict):
            return result

        return None

    # ============================================================
    # Fallback Query
    # ============================================================

    def _build_fallback_query(
        self,
        requirement: DatasetRequirement,
    ) -> str:

        parts = []

        if requirement.domain:
            parts.append(
                requirement.domain
            )

        if requirement.modality:
            parts.append(
                requirement.modality
            )

        parts.extend(
            requirement.classes[:5]
        )

        parts.extend(
            requirement.columns[:5]
        )

        query = " ".join(
            str(part)
            for part in parts
            if part
        )

        return query.strip()

    # ============================================================
    # Deduplicate
    # ============================================================

    def _deduplicate(
        self,
        candidates: list[DatasetCandidate],
    ) -> list[DatasetCandidate]:

        unique = {}
        
        for candidate in candidates:

            key = (
                candidate.source,
                candidate.dataset_id,
            )

            if key not in unique:
                unique[key] = candidate

        return list(
            unique.values()
        )

    # ============================================================
    # Integer Conversion
    # ============================================================

    @staticmethod
    def _to_int(
        value: Any,
    ) -> int:

        try:

            if value is None:
                return 0

            return int(value)

        except (
            TypeError,
            ValueError,
        ):

            return 0